#!/usr/bin/env python3
"""Multi-source box-office averaging engine for FlickAtlas.

Reads per-source day-wise JSON files from a staging directory, averages
the Rs Cr figure for each movie+day across every source that reports it,
and writes the finalized js/daywise-data.js in the EXACT existing format
(window.FA_DAYWISE, collection in USD at 94.65 Rs/USD).

Averaging rule (registry ~/workspace/boxoffice-sources/boxoffice-sources.json):
  * For each movie (TMDB id) + day, collect the Rs Cr figure from every
    source that reports it.
  * If 2+ sources report the same movie+day, take the MEAN.
  * If only 1 source reports it, use that figure.
  * Normalize all figures to Rs Cr, INDIA NET, before averaging.
    Worldwide gross figures are NEVER averaged into day-wise — they are
    a different number (see the scope guard below).
  * Never invent a figure — a movie+day with no source data stays absent.

SOURCE-AGNOSTIC: the engine reads whatever per-source JSON files exist in
the staging dir. A new site is added by dropping in its reader output —
no code change is needed. A source that is temporarily down simply has
no (or a stale) staging file: it is skipped, the other sources are used,
and the skip is logged.

Per-source staging format (one file per source, filename = source id):
    {"tmdb_id": [{"day": N, "date": "YYYY-MM-DD",
                   "collection_inr_cr": X.XX, "source": "<site-id>"}]}
  * "day" may be a number or a "Day N" string (both accepted).
  * "collection_inr_cr" must be the INDIA NET day-wise figure in Rs Cr.
    Running totals, weekend totals and worldwide grosses MUST NOT be
    written here — the reader is responsible for scope normalization.
  * Staging files MUST be deterministic: sorted by tmdb_id and day, no
    timestamps, no run-specific data. A staging file whose content did
    not change must be byte-identical to the previous run, or the
    hourly pipeline will commit (and deploy) every hour for nothing.

OPTIONAL EXTRA FIELDS (per row, all grounded-only, never estimated):
  * "overseas_inr_cr": overseas GROSS for the day, Rs Cr (Sacnilk
    quicknews overseas-standing sentence; Tavily+Gemini search
    extraction). Averaged across sources that report it, like India
    Net. A row may carry ONLY extras (no collection_inr_cr) — an
    extras-only row updates just those fields of the baseline row and
    never touches the India figure.
  * "shows": shows screened that day, India (int).
  * "occupancy_pct": overall occupancy that day, % (0-100, 1dp).
  * "tickets": tickets sold (footfalls) that day, India (int).
  Extra fields are averaged across the sources that report each field
  (mean; shows/tickets rounded to int, occupancy to 1dp, overseas to
  2dp Rs Cr). A field with no source stays absent — never 0, never
  invented. When a new staging row has no value for a field, the
  baseline row keeps its existing value for that field.

Reader contract (what a per-site reader must do — see README in
~/workspace/boxoffice-sources/):
  * CLI:  python3 scripts/<reader>.py --stage out/boxoffice-staging
  * Writes out/boxoffice-staging/<source-id>.json in the format above.
  * Exit 0 on success; non-zero on failure (the pipeline continues
    with the other sources — a failed reader never blocks the run).
  * Must use a browser User-Agent where the site blocks bare clients.

Merge behaviour: the engine MERGES into the existing daywise-data.js
(the baseline). A movie+day present in staging is finalized from the
staging figures (replacing the baseline row when the value differs).
A movie+day with NO staging data is PRESERVED as-is from the baseline
(it was finalized by an earlier run). The engine never deletes rows.

Sidecar: out/multisource-boxoffice.json records, for every movie+day
finalized from staging data in this run, the sources that contributed
and their Rs Cr figures. It is deterministic (no timestamps, sorted
keys) so it only changes when provenance actually changes — it never
forces a spurious hourly commit.

This file is stdlib only. It is the SOLE writer of js/daywise-data.js
once the multi-source pipeline is live (the Sacnilk reader writes its
staging file with --stage and the engine finalizes from it).
"""

import argparse
import json
import math
import os
import re
import sys
from datetime import date

INR_PER_USD = 94.65  # site FA_RATES — same as sacnilk_boxoffice.py

# The daywise header is byte-identical to apply-auto.py's and
# sacnilk_boxoffice.py's ON PURPOSE: all writers must emit the same
# header, or the file flip-flops between headers on every hourly run
# (a spurious diff + deploy).
DAYWISE_HEADER = (
    "/* FlickAtlas — day-wise box office data. GENERATED by the "
    "auto-pipeline (scripts/gemini_batch.py + scripts/apply-auto.py) "
    "from reconciled post data — do not edit by hand. Keyed by TMDB "
    "movie id; collection = India Net USD for the day; overseas = "
    "overseas gross USD for the day when reported; shows / occupancy "
    "/ tickets = India figures for the day when reported. */")

# A single day's India Net collection has never exceeded ~Rs 85 Cr
# (Jawan / Pathaan Day 1). Anything above this is almost certainly a
# WORLDWIDE figure, a running total, or a unit error — reject it
# rather than average a wrong number into the site.
MAX_DAY_CR = 120.0
# Sanity caps for the optional extra fields (same purpose: reject a
# running total or unit error misread as a day figure).
MAX_SHOWS = 30000        # most shows in a day: ~16.5k (Jailer 2 Day 1)
MAX_TICKETS = 5000000    # most footfalls in a day: ~1.0M (Jailer 2 Day 9)
MAX_OCCUPANCY = 100.0

# Optional extra fields: (staging key, daywise key, kind, cap).
# kind "crore" = Rs Cr -> USD at INR_PER_USD (like India Net);
# kind "int" = integer count, averaged then rounded;
# kind "pct" = percentage, averaged to 1dp.
EXTRA_FIELDS = (
    ("overseas_inr_cr", "overseas", "crore", MAX_DAY_CR),
    ("shows", "shows", "int", MAX_SHOWS),
    ("occupancy_pct", "occupancy", "pct", MAX_OCCUPANCY),
    ("tickets", "tickets", "int", MAX_TICKETS),
)

DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
DAY_RE = re.compile(r"(\d+)")


# --- js map read/write (verbatim from sacnilk_boxoffice.py) ------------
# Copied, not imported: the engine must emit byte-identical output.

def read_js_map(path, var):
    """Parse `window.VAR = {...};` into a dict. Returns {} if missing."""
    if not os.path.exists(path):
        return {}
    with open(path, encoding="utf-8") as f:
        raw = f.read()
    start = raw.index("{")
    end = raw.rindex("}")
    return json.loads(raw[start:end + 1])


def write_js_map(path, var, data, header):
    content = (header + f"\nwindow.{var} = " +
               json.dumps(data, ensure_ascii=False, indent=2) + ";\n")
    existing = ""
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            existing = f.read()
    if existing == content:
        return False
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    return True


def write_json_if_changed(path, data):
    """Write a deterministic JSON file only when its content differs
    (so an unchanged file never triggers a spurious pipeline commit)."""
    content = json.dumps(data, ensure_ascii=False, indent=2,
                         sort_keys=True) + "\n"
    existing = ""
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            existing = f.read()
    if existing == content:
        return False
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    return True


# --- validation ---------------------------------------------------------

def parse_day(value):
    """Accept an int day or a 'Day N' string; return int or None."""
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        return value if value >= 1 else None
    if isinstance(value, str):
        m = DAY_RE.search(value)
        if m:
            n = int(m.group(1))
            return n if n >= 1 else None
    return None


def parse_date(value, today):
    """Return a valid YYYY-MM-DD date string not in the future, else None."""
    if not isinstance(value, str):
        return None
    s = value.strip()
    if not DATE_RE.match(s):
        return None
    try:
        d = date.fromisoformat(s)
    except ValueError:
        return None
    if d > today:
        return None
    return s


def parse_crore(value):
    """Return a finite positive Rs Cr number, else None."""
    try:
        cr = float(value)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(cr) or cr <= 0:
        return None
    return cr


def parse_extras(row):
    """Valid optional extra fields from a staging row.

    Returns {staging_key: value} for the fields that are present and
    sane; an absent/invalid field is simply omitted (never 0, never
    invented). Overseas is a Rs Cr figure (same cap as India Net);
    shows/tickets are counts; occupancy is a 0-100 percentage.
    A value above its sanity cap is dropped (likely a running total
    or unit error misread as a day figure)."""
    out = {}
    for staging_key, _day_key, kind, cap in EXTRA_FIELDS:
        raw = row.get(staging_key)
        if raw is None:
            continue
        try:
            v = float(raw)
        except (TypeError, ValueError):
            continue
        if not math.isfinite(v) or v <= 0 or v > cap:
            continue
        if kind == "int":
            out[staging_key] = int(round(v))
        elif kind == "pct":
            out[staging_key] = round(v, 1)
        else:  # crore
            out[staging_key] = round(v, 2)
    return out


# --- staging ------------------------------------------------------------

def load_staging(staging_dir, today, published, primary):
    """Read every *.json in the staging dir.

    Returns (collected, extras_collected, skipped_files, rejected)
    where collected is {(tmdb_id, day): {source_id: (crore, date)}}
    for the India Net figure, and extras_collected is
    {(tmdb_id, day): {source_id: ({staging_key: value}, date)}} for
    the optional extra fields. A row may contribute India only,
    extras only, or both. The filename stem is the authoritative
    source id; a row's own "source" field is informational only.
    """
    collected = {}
    extras_collected = {}
    skipped_files = []
    rejected = []
    if not os.path.isdir(staging_dir):
        print(f"multisource: staging dir {staging_dir} does not exist — "
              "no per-source data, nothing to do")
        return collected, extras_collected, skipped_files, rejected
    names = sorted(f for f in os.listdir(staging_dir)
                   if f.endswith(".json"))
    if not names:
        print("multisource: no staging files found — nothing to do")
        return collected, extras_collected, skipped_files, rejected
    for name in names:
        source_id = name[:-len(".json")]
        path = os.path.join(staging_dir, name)
        try:
            with open(path, encoding="utf-8") as f:
                data = json.load(f)
        except (OSError, ValueError) as e:
            print(f"multisource: SKIP {name} (unreadable: {e}) — "
                  "source treated as down, using the others")
            skipped_files.append(name)
            continue
        if not isinstance(data, dict):
            print(f"multisource: SKIP {name} (top level is not an object)")
            skipped_files.append(name)
            continue
        rows_in = 0
        for tid, rows in data.items():
            tid = str(tid).strip()
            if published is not None and tid not in published:
                rejected.append((source_id, tid, None,
                                 "film not published"))
                continue
            if not isinstance(rows, list):
                rejected.append((source_id, tid, None,
                                 "rows are not a list"))
                continue
            seen_days = set()
            for row in rows:
                if not isinstance(row, dict):
                    rejected.append((source_id, tid, None,
                                     "row is not an object"))
                    continue
                day = parse_day(row.get("day"))
                if day is None:
                    rejected.append((source_id, tid, None,
                                     f"bad day {row.get('day')!r}"))
                    continue
                if day in seen_days:
                    print(f"multisource: WARN {name} {tid} Day {day}: "
                          "duplicate row in one source file — keeping last")
                seen_days.add(day)
                dstr = parse_date(row.get("date"), today)
                if dstr is None:
                    rejected.append((source_id, tid, day,
                                     f"bad/future date "
                                     f"{row.get('date')!r}"))
                    continue
                cr = parse_crore(row.get("collection_inr_cr"))
                extras = parse_extras(row)
                if cr is None and not extras:
                    rejected.append((source_id, tid, day,
                                     "collection_inr_cr missing/zero "
                                     "and no extras"))
                    continue
                if cr is not None and cr > MAX_DAY_CR:
                    rejected.append((source_id, tid, day,
                                     f"Rs{cr:.2f} Cr exceeds the "
                                     f"single-day India Net cap "
                                     f"({MAX_DAY_CR:.0f} Cr) — likely a "
                                     "worldwide or running total, "
                                     "rejected"))
                    continue
                row_source = row.get("source")
                if row_source and str(row_source) != source_id:
                    print(f"multisource: WARN {name} {tid} Day {day}: "
                          f"row source {row_source!r} != filename "
                          f"{source_id!r} — using filename")
                if cr is not None:
                    key = (tid, day)
                    slot = collected.setdefault(key, {})
                    slot[source_id] = (cr, dstr)
                if extras:
                    xkey = (tid, day)
                    xslot = extras_collected.setdefault(xkey, {})
                    xslot[source_id] = (extras, dstr)
                rows_in += 1
        print(f"multisource: {name}: {rows_in} valid row(s)")
    return collected, extras_collected, skipped_files, rejected


def pick_date(contributions, primary):
    """Choose the date for a finalized row when sources disagree.

    Prefer the primary source's date (Sacnilk — it anchors Day 1 from
    its own page); otherwise the most common date; ties go to the
    earliest date. Returns (date_str, disagreed_bool).
    """
    dates = [d for (_cr, d) in contributions.values()]
    if primary in contributions:
        chosen = contributions[primary][1]
        return chosen, len(set(dates)) > 1
    counts = {}
    for d in dates:
        counts[d] = counts.get(d, 0) + 1
    best = max(counts.values())
    candidates = sorted(d for d, c in counts.items() if c == best)
    return candidates[0], len(set(dates)) > 1


def finalize_extras(extras_collected):
    """Mean each extra field across the sources reporting it.

    Returns {(tmdb_id, day): {daywise_key: {"value": ..., "crore": ...,
    "sources": {source_id: raw}}}}. "value" is the daywise-data.js
    value (USD int for overseas, int for shows/tickets, 1dp float
    for occupancy); "crore" is the Rs Cr mean, present only for the
    overseas (crore-kind) field. A field no source reports is absent.
    """
    out = {}
    for (tid, day), by_source in sorted(extras_collected.items()):
        per_field = {}
        for skey, dkey, kind, _cap in EXTRA_FIELDS:
            vals = [(s, src[skey]) for s, (src, _d)
                    in by_source.items() if skey in src]
            if not vals:
                continue
            nums = [v for (_s, v) in vals]
            if kind == "crore":
                mean_cr = round(sum(nums) / len(nums), 2)
                value = round(mean_cr * 1e7 / INR_PER_USD)
                per_field[dkey] = {"value": value, "crore": mean_cr,
                                   "sources": {s: v for s, v in vals}}
            elif kind == "int":
                value = int(round(sum(nums) / len(nums)))
                per_field[dkey] = {"value": value,
                                   "sources": {s: v for s, v in vals}}
            else:  # pct
                value = round(sum(nums) / len(nums), 1)
                per_field[dkey] = {"value": value,
                                   "sources": {s: v for s, v in vals}}
        if per_field:
            out[(tid, day)] = per_field
    return out


def finalize(collected, extras_collected, primary):
    """Compute the finalized figure for each (tmdb_id, day).

    Returns {tmdb_id: {day: {"date", "collection_inr_cr",
    "collection_usd", "sources": {source_id: crore}, "india": bool,
    "extras": {daywise_key: {"value", "crore"?, "sources"}}}}}.
    "india" is False for extras-only entries (no India Net figure
    this run — the merge must not touch the baseline India figure
    for those days). "extras" is present only when at least one
    extra field was reported for the day.
    """
    out = {}
    for (tid, day), contribs in sorted(collected.items()):
        crs = [cr for (cr, _d) in contribs.values()]
        if len(crs) >= 2:
            mean_cr = round(sum(crs) / len(crs), 2)
        else:
            mean_cr = round(crs[0], 2)
        usd = round(mean_cr * 1e7 / INR_PER_USD)
        dstr, disagreed = pick_date(contribs, primary)
        if disagreed:
            print(f"multisource: WARN {tid} Day {day}: sources disagree "
                  f"on date {sorted(set(d for (_c, d) in contribs.values()))} "
                  f"— using {dstr}")
        per_movie = out.setdefault(tid, {})
        per_movie[day] = {
            "date": dstr,
            "collection_inr_cr": mean_cr,
            "collection_usd": usd,
            "sources": {s: cr for s, (cr, _d) in
                        sorted(contribs.items())},
            "india": True,
        }
    extra_means = finalize_extras(extras_collected)
    for (tid, day), fields in extra_means.items():
        per_movie = out.setdefault(tid, {})
        if day in per_movie:
            per_movie[day]["extras"] = fields
        else:
            # Extras-only: date from the extras sources (most common,
            # ties -> earliest). The merge will NOT overwrite the
            # baseline date from an extras-only entry.
            dates = [d for (_ex, d) in extras_collected[(tid, day)].values()]
            counts = {}
            for d in dates:
                counts[d] = counts.get(d, 0) + 1
            best = max(counts.values())
            dstr = sorted(d for d, c in counts.items()
                          if c == best)[0]
            per_movie[day] = {"date": dstr, "india": False,
                              "extras": fields}
    return out


def merge_into_baseline(daywise, finalized):
    """Merge finalized figures into the baseline FA_DAYWISE map.

    Same rules as sacnilk_boxoffice.merge_daywise: an existing row for
    the same film+day is UPDATED only when the value differs (date is
    updated with it); otherwise the row is APPENDED and days sorted.
    Rows with no staging data are preserved untouched.
    Extra fields: a finalized extra UPDATES the row's field when it
    differs; a missing extra PRESERVES the baseline value (never
    wiped). An extras-only entry with no baseline row is skipped
    (a day-wise row cannot be created from extras alone).
    Returns (added, updated, unchanged).
    """
    added, updated, unchanged = 0, 0, 0
    for tid, days in finalized.items():
        rows_list = daywise.setdefault(tid, [])
        for day, fig in sorted(days.items()):
            is_india = fig.get("india", True)
            extras = fig.get("extras") or {}
            hit = None
            for r in rows_list:
                if r.get("day") == f"Day {day}":
                    hit = r
                    break
            if hit is None:
                if not is_india:
                    print(f"multisource: WARN {tid} Day {day}: "
                          "extras-only, no baseline row — skipped")
                    continue
                entry = {"date": fig["date"],
                         "day": f"Day {day}",
                         "collection": int(fig["collection_usd"])}
                for dkey, fdata in extras.items():
                    entry[dkey] = fdata["value"]
                rows_list.append(entry)
                rows_list.sort(key=lambda r: int(
                    re.sub(r"\D", "", r.get("day", "0")) or 0))
                added += 1
                continue
            changed = False
            if is_india:
                if hit.get("collection") != int(fig["collection_usd"]):
                    hit["collection"] = int(fig["collection_usd"])
                    hit["date"] = fig["date"]
                    changed = True
            for dkey, fdata in extras.items():
                if hit.get(dkey) != fdata["value"]:
                    hit[dkey] = fdata["value"]
                    changed = True
            if changed:
                updated += 1
            else:
                unchanged += 1
    return added, updated, unchanged


def main():
    ap = argparse.ArgumentParser(
        description="Multi-source box-office averaging engine: read "
                    "per-source staging JSON, average Rs Cr per "
                    "movie+day, write the finalized js/daywise-data.js.")
    ap.add_argument("--root", default=None,
                    help="repo root (default: parent of this script's dir)")
    ap.add_argument("--staging", default=None,
                    help="staging dir with per-source JSON files "
                         "(default: <root>/out/boxoffice-staging)")
    ap.add_argument("--daywise", default=None,
                    help="js/daywise-data.js path "
                         "(default: <root>/js/daywise-data.js)")
    ap.add_argument("--published", default=None,
                    help="js/published-titles.js path "
                         "(default: <root>/js/published-titles.js)")
    ap.add_argument("--sidecar", default=None,
                    help="provenance sidecar path "
                         "(default: <root>/out/multisource-boxoffice.json)")
    ap.add_argument("--primary", default="sacnilk",
                    help="source id whose date wins on disagreement "
                         "(default: sacnilk)")
    ap.add_argument("--dry-run", action="store_true",
                    help="print what it would write, write nothing")
    ap.add_argument("--today", default=None,
                    help="override run date YYYY-MM-DD (testing)")
    args = ap.parse_args()

    today = (date.fromisoformat(args.today) if args.today
             else date.today())
    root = args.root or os.path.dirname(
        os.path.dirname(os.path.abspath(__file__)))
    staging_dir = args.staging or os.path.join(
        root, "out", "boxoffice-staging")
    day_path = args.daywise or os.path.join(root, "js", "daywise-data.js")
    pub_path = args.published or os.path.join(
        root, "js", "published-titles.js")
    sidecar_path = args.sidecar or os.path.join(
        root, "out", "multisource-boxoffice.json")

    # Published gate: only finalize rows for published titles
    # (same gate as sacnilk_boxoffice.merge_daywise).
    published = None
    if os.path.exists(pub_path):
        pub = read_js_map(pub_path, "FA_PUBLISHED")
        published = set(str(k) for k in pub.keys())
        print(f"multisource: {len(published)} published title(s)")
    else:
        print(f"multisource: WARN {pub_path} not found — published "
              "gate disabled (all staging rows accepted)")

    daywise = read_js_map(day_path, "FA_DAYWISE")
    print(f"multisource: baseline daywise-data.js: "
          f"{len(daywise)} movie(s), "
          f"{sum(len(v) for v in daywise.values())} row(s)")

    collected, extras_collected, skipped_files, rejected = load_staging(
        staging_dir, today, published, args.primary)
    if not collected and not extras_collected:
        print("multisource: no valid staging rows — daywise-data.js "
              "left untouched")
        for src, tid, day, why in rejected:
            print(f"  rejected: {src} {tid} "
                  f"{'Day ' + str(day) if day else ''}: {why}")
        return 0

    finalized = finalize(collected, extras_collected, args.primary)
    n_figs = sum(len(v) for v in finalized.values())
    n_multi = sum(1 for days in finalized.values()
                  for f in days.values()
                  if f.get("india") and len(f.get("sources", {})) >= 2)
    n_extra = sum(1 for days in finalized.values()
                  for f in days.values() if f.get("extras"))
    print(f"multisource: finalized {n_figs} movie+day figure(s) from "
          f"{len(collected)} collected ({n_multi} averaged across 2+ "
          f"sources, {n_figs - n_multi} single-source; {n_extra} with "
          f"extra fields)")

    added, updated, unchanged = merge_into_baseline(daywise, finalized)
    print(f"multisource: merge: +{added} new, {updated} updated, "
          f"{unchanged} unchanged (baseline rows with no staging data "
          "preserved)")

    for src, tid, day, why in rejected:
        print(f"  rejected: {src} {tid} "
              f"{'Day ' + str(day) if day else ''}: {why}")
    if skipped_files:
        print(f"multisource: skipped files (source down): "
              f"{', '.join(skipped_files)}")

    if args.dry_run:
        print("multisource: DRY-RUN — nothing written")
        return 0

    changed = write_js_map(day_path, "FA_DAYWISE", daywise,
                           DAYWISE_HEADER)
    print(f"multisource: daywise-data.js written: {changed}")

    sidecar = {
        "rule": ("mean of the Rs Cr figures across every source that "
                 "reports a movie+day; single source = that figure; "
                 "India Net day-wise only; never invented. Extra fields "
                 "(overseas/shows/occupancy/tickets) are averaged the "
                 "same way across the sources that report each field; "
                 "a missing field stays absent."),
        "figures": {
            tid: {str(day): fig for day, fig in sorted(days.items())}
            for tid, days in sorted(finalized.items())
        },
    }
    side_changed = write_json_if_changed(sidecar_path, sidecar)
    print(f"multisource: sidecar {sidecar_path} written: {side_changed}")
    return 0


