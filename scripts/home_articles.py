#!/usr/bin/env python3
"""Build js/home-articles-data.js — the homepage's slim article subset.

The homepage (index.html) used to load js/articles-data.js
(window.FA_ARTICLES — every published article INCLUDING the full
`body` text; ~2.8 MB raw) as a plain blocking <script> before
js/page-index.js, so on a slow connection every homepage rail waited
on that one file and the categories appeared missing.

The homepage never reads article bodies. Its proven needs
(js/page-index.js + js/trending-searches.js) are, per article:
  id, type, headline, dek, entities, keywords, images, published
  - Trending News / Latest News slider: the articles themselves come
    from the /api/news feed; FA_ARTICLES only supplies the thumbnail
    (images[0].url) per feed id.
  - Drama Episodes rail: built from the article map directly —
    headline (the "— Watch Online on <channel>" matcher), published,
    images[0].url + images[0].source, entities.titles[0].
  - Trending Topics vetting: headline + published per article id.

This module projects the newest articles (by `published`, newest
first — the same ordering js/page-index.js applies) onto those
fields only, dropping `body` and `facts` (together ~85% of the full
file's bytes), and writes the result as window.FA_HOME_ARTICLES.

Selection is two-part:
  - the newest HOME_LIMIT = 120 articles overall — at the pipeline's
    4 posts/hour pace that covers the full rolling 24 h news window
    (~96-100 posts/day) with room to spare; the homepage displays at
    most 15 news items;
  - PLUS the newest HOME_EPISODE_LIMIT = 40 episode posts (headline
    matches the same "Watch Online on" pattern the homepage rail
    uses), however deep they sit: episode posts are only ~13/day
    against ~100 articles/day, so the 14th-newest episode — the
    homepage rail shows 14 — regularly sits just beyond the
    newest-120 cut, and the rail also gates on a 7-day airing window
    that a ~28 h slice cannot serve. 40 episodes reach ~5 days back.

Writers of js/articles-data.js call write_home_articles() right after
their own write (scripts/apply-auto.py, scripts/episode-guides.py,
scripts/apply-publish.py, scripts/refresh-keywords.py); the hourly
workflow also runs this file as a step before the commit, so the
subset can never go stale against the full file. Running it by hand
rebuilds the subset from the current js/articles-data.js:

    python3 scripts/home_articles.py

Stdlib only; writes the file only when its content changed.
"""
import json
import os
import re
import sys
from datetime import timezone
from email.utils import parsedate_to_datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ARTICLES_JS = os.path.join(ROOT, "js", "articles-data.js")
HOME_JS = os.path.join(ROOT, "js", "home-articles-data.js")

HOME_LIMIT = 120
HOME_EPISODE_LIMIT = 40
# The homepage Drama Episodes rail's own headline test
# (js/page-index.js epArticles): an episode post is one whose
# headline carries "Watch on <channel>" / "Watch Online on <channel>".
EPISODE_HEADLINE_RE = re.compile(r"watch (?:online )?on\b", re.I)
# The homepage-proven field set (see module docstring). Order here is
# the key order written per record; fields absent from a source
# record stay absent (never invented).
HOME_FIELDS = ("id", "type", "headline", "dek", "entities",
               "keywords", "images", "published")

HEADER = ("/* FlickAtlas — homepage article subset: newest "
          f"{HOME_LIMIT} articles + newest {HOME_EPISODE_LIMIT} "
          "episode posts, slim fields only (no body/facts). "
          "GENERATED by scripts/home_articles.py from "
          "js/articles-data.js — do not edit by hand. */")


def parse_ts(value):
    """`published` -> epoch seconds (float), 0 when unparseable.

    Records carry ISO strings ("2026-10-24T14:45:34Z") and a few
    legacy RFC 2822 strings ("Wed, 28 Oct 2026 23:50:12 GMT") — the
    same two shapes JS Date.parse accepts in js/page-index.js, whose
    episode sort this ordering mirrors."""
    s = str(value or "").strip()
    if not s:
        return 0.0
    try:
        from datetime import datetime
        dt = datetime.fromisoformat(s.replace("Z", "+00:00"))
    except ValueError:
        try:
            dt = parsedate_to_datetime(s)
        except (TypeError, ValueError):
            return 0.0
    if dt is None:
        return 0.0
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt.timestamp()


def build_home_articles(articles, limit=HOME_LIMIT,
                        episode_limit=HOME_EPISODE_LIMIT):
    """{id: full record} -> {id: slim record}: the newest `limit`
    articles overall, union the newest `episode_limit` episode posts.

    Ordering: published desc, then id asc — identical to the episode
    sort in js/page-index.js (Date.parse desc, id localeCompare), so
    the subset's first entries are exactly the ones the homepage
    rails pick. The output dict keeps that newest-first order."""
    def sort_key(item):
        aid, rec = item
        return (-parse_ts((rec or {}).get("published")), str(aid))

    ordered = sorted(articles.items(), key=sort_key)
    picked = {str(aid) for aid, _ in ordered[:limit]}
    episodes_in = 0
    for aid, rec in ordered:
        if not isinstance(rec, dict):
            continue
        if not EPISODE_HEADLINE_RE.search(str(rec.get("headline") or "")):
            continue
        if str(aid) in picked:
            episodes_in += 1
        elif episodes_in < episode_limit:
            picked.add(str(aid))
            episodes_in += 1

    out = {}
    for aid, rec in ordered:
        if str(aid) not in picked or not isinstance(rec, dict):
            continue
        slim = {k: rec[k] for k in HOME_FIELDS if k in rec}
        out[str(aid)] = slim
    return out


def read_js_map(path, var):
    """Parse `window.VAR = {...};` into a dict. Returns {} if missing."""
    if not os.path.exists(path):
        return {}
    with open(path, encoding="utf-8") as f:
        raw = f.read()
    start = raw.index("{")
    end = raw.rindex("}")
    return json.loads(raw[start:end + 1])


def write_home_articles(root=ROOT, articles=None):
    """(Re)write <root>/js/home-articles-data.js. Returns True when
    the file changed. `articles` may pass the caller's in-memory
    FA_ARTICLES map; otherwise the map is read from disk."""
    if articles is None:
        articles = read_js_map(os.path.join(root, "js", "articles-data.js"),
                               "FA_ARTICLES")
    subset = build_home_articles(articles)
    content = (HEADER + "\nwindow.FA_HOME_ARTICLES = " +
               json.dumps(subset, ensure_ascii=False, indent=2) + ";\n")
    path = os.path.join(root, "js", "home-articles-data.js")
    existing = ""
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            existing = f.read()
    if existing == content:
        return False
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    return True


def main():
    articles = read_js_map(ARTICLES_JS, "FA_ARTICLES")
    changed = write_home_articles(ROOT, articles)
    subset = build_home_articles(articles)
    print(f"home-articles: {len(subset)} of {len(articles)} articles "
          f"-> js/home-articles-data.js (changed: {changed})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
