#!/usr/bin/env python3
"""Publish chosen TMDB titles into js/published-titles.js.

FlickAtlas is published-only: TMDB is a data source, not a catalogue.
This script fetches ONLY the titles somebody chose (TMDB ids on the
command line) and writes/updates their entries in js/published-titles.js
(window.FA_PUBLISHED) — the single source of truth for everything the
site shows. It never fetches a title nobody chose and never deletes
entries.

For each id it fetches TMDB details (movie first, then tv) with
videos (+ release_dates for movies, + content_ratings for tv),
picks the OFFICIAL trailer (type=Trailer, official=true, site=YouTube),
derives the industry (bollywood / pakistani / world), picks the
certification, and stores the baked-in record — including the rich
detail fields (budget, revenue, genres, runtime, tagline, status,
production countries, spoken languages, seasons, creators) — that the
site renders from. Re-running the same ids is a no-op when nothing
changed.

Usage:
  TMDB_API_KEY=<key> publish-titles.py 1375156 1654581
  publish-titles.py --key <key> --out js/published-titles.js 1375156
  publish-titles.py --categories movies,trending --published-at 2026-10-23 1375156

Exits 0; prints what it did. Writes the file only when something changed.
The TMDB key comes from the TMDB_API_KEY environment variable or --key —
it is never hardcoded in this script.
"""
import argparse
import json
import os
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_OUT = os.path.join(ROOT, "js", "published-titles.js")

HEADER = ("/* FlickAtlas — published titles. GENERATED by the pipeline "
          "(scripts/publish-titles.py) — do not edit by hand. Keyed by "
          "TMDB id; the single source of truth for everything the site "
          "shows. TMDB is a data source only — a title appears here only "
          "because it was chosen and published. Trailer is the official "
          "YouTube trailer, or null when TMDB has none. Rich detail "
          "fields (budget, revenue, genres, runtime, tagline, status, "
          "production countries, spoken languages, seasons, creators, "
          "certification) are baked in at publish time so the detail "
          "pages render maximum detail without a live TMDB call. */")

TMDB_BASE = "https://api.themoviedb.org/3"


def read_js_map(path, var):
    """Parse `window.VAR = {...};` into a dict. Returns {} if missing."""
    if not os.path.exists(path):
        return {}
    with open(path, encoding="utf-8") as f:
        raw = f.read()
    start = raw.index("{")
    end = raw.rindex("}")
    return json.loads(raw[start:end + 1])


def write_js_map(path, var, data, header):
    content = (header + f"\nwindow.{var} = " +
               json.dumps(data, ensure_ascii=False, indent=2) + ";\n")
    existing = ""
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            existing = f.read()
    if existing == content:
        return False
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    return True


def tmdb_get(path, key):
    """GET one TMDB endpoint. Returns the parsed JSON, or None on 404."""
    url = (TMDB_BASE + path +
           ("&" if "?" in path else "?") +
           "api_key=" + urllib.parse.quote(key))
    req = urllib.request.Request(url, headers={
        "Accept": "application/json",
        "User-Agent": "FlickAtlas-publish-titles/1.0",
    })
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return json.load(r)
    except urllib.error.HTTPError as e:
        if e.code == 404:
            return None
        raise


def fetch_title(tid, key):
    """Fetch a title's TMDB details (+videos, +release_dates /
    content_ratings for certification). Movie first, then tv.

    Returns (details_dict, "movie"|"tv"), or (None, None) when the id
    exists as neither.
    """
    d = tmdb_get(f"/movie/{tid}?append_to_response=videos,release_dates",
                 key)
    if d is not None:
        return d, "movie"
    d = tmdb_get(f"/tv/{tid}?append_to_response=videos,content_ratings",
                 key)
    if d is not None:
        return d, "tv"
    return None, None


def pick_trailer(details):
    """The OFFICIAL YouTube trailer, or None when TMDB has none."""
    vids = (details.get("videos") or {}).get("results") or []
    for v in vids:
        if (v.get("type") == "Trailer" and v.get("official")
                and v.get("site") == "YouTube" and v.get("key")):
            return {"key": v["key"],
                    "name": v.get("name") or "",
                    "site": "YouTube"}
    return None


def pick_release_date(details, media_type):
    """Baked release date for a movie: India theatrical (type 3, IN)
    first, then the earliest theatrical date in any region, then the
    TMDB primary date. A festival premiere (type 1) or limited
    release (type 2) must never be the baked date when a theatrical
    date exists — the primary date IS often the festival premiere
    (e.g. Hotel Utopia: only a DOK Leipzig premiere exists, so no
    theatrical date is available anywhere and the primary date is
    still used — see the note in build_entry). TV: first_air_date,
    unchanged."""
    if media_type != "movie":
        return details.get("first_air_date") or ""
    results = ((details.get("release_dates") or {}).get("results")
               or [])

    def theatrical_dates(entry):
        out = []
        for r in (entry or {}).get("release_dates") or []:
            if r.get("type") == 3 and r.get("release_date"):
                out.append(str(r["release_date"])[:10])
        return sorted(out)

    by_country = {str(r.get("iso_3166_1") or "").upper(): r
                  for r in results}
    in_theatrical = theatrical_dates(by_country.get("IN"))
    if in_theatrical:
        return in_theatrical[0]
    all_theatrical = sorted(
        d for r in results for d in theatrical_dates(r))
    if all_theatrical:
        return all_theatrical[0]
    return details.get("release_date") or ""


def pick_certification(details, media_type):
    """Theatrical/content certification, or "" when TMDB has none.

    Movie: release_dates results — prefer the IN theatrical (type 3)
    certification, then any IN certification, then US theatrical, then
    any certification at all. TV: content_ratings results — prefer IN,
    then US.
    """
    if media_type == "movie":
        results = ((details.get("release_dates") or {}).get("results")
                   or [])
        def cert_of(entry):
            if not entry:
                return ""
            for r in entry.get("release_dates") or []:
                if r.get("type") == 3 and r.get("certification"):
                    return r["certification"]
            for r in entry.get("release_dates") or []:
                if r.get("certification"):
                    return r["certification"]
            return ""
        by_country = {str(r.get("iso_3166_1") or "").upper(): r
                      for r in results}
        return (cert_of(by_country.get("IN"))
                or cert_of(by_country.get("US"))
                or next((cert_of(r) for r in results if cert_of(r)), ""))
    results = ((details.get("content_ratings") or {}).get("results")
               or [])
    by_country = {str(r.get("iso_3166_1") or "").upper(): r
                  for r in results}
    for cc in ("IN", "US"):
        entry = by_country.get(cc)
        if entry and entry.get("rating"):
            return entry["rating"]
    for r in results:
        if r.get("rating"):
            return r["rating"]
    return ""


def derive_industry(details):
    """bollywood = Hindi-language, India origin.
    pakistani = Pakistan origin (any language) OR Urdu-language.
    world = everything else."""
    lang = str(details.get("original_language") or "").lower()
    countries = [str(c).upper()
                 for c in (details.get("origin_country") or [])]
    if not countries:
        countries = [str(c.get("iso_3166_1") or "").upper()
                     for c in (details.get("production_countries") or [])]
    if "PK" in countries or lang == "ur":
        return "pakistani"
    if lang == "hi" and "IN" in countries:
        return "bollywood"
    return "world"


def build_entry(details, media_type, categories, published_at):
    """Build the FA_PUBLISHED entry for one title (spec §1a fields,
    including the RICH DETAIL FIELDS — baked in here so the detail
    pages render maximum detail without a live TMDB call)."""
    entry = {
        "id": details["id"],
        "type": media_type,
        "title": details.get("title") or details.get("name") or "",
        "poster_path": details.get("poster_path"),
        "backdrop_path": details.get("backdrop_path"),
        "vote_average": details.get("vote_average"),
        "vote_count": details.get("vote_count"),
        "overview": details.get("overview") or "",
        "industry": derive_industry(details),
        "original_language": details.get("original_language") or "",
        "origin_country": list(details.get("origin_country") or []),
        "trailer": pick_trailer(details),
        "categories": list(categories),
        "published_at": published_at,
        "source": "tmdb",
        # --- rich detail fields (spec §1a) ---
        "budget": details.get("budget") or 0,
        "revenue": details.get("revenue") or 0,
        "genres": [g.get("name") for g in (details.get("genres") or [])
                   if g.get("name")],
        "tagline": details.get("tagline") or "",
        "status": details.get("status") or "",
        "production_countries": [
            c.get("iso_3166_1") for c in
            (details.get("production_countries") or [])
            if c.get("iso_3166_1")],
        "spoken_languages": [
            l.get("iso_639_1") for l in
            (details.get("spoken_languages") or [])
            if l.get("iso_639_1")],
        "certification": pick_certification(details, media_type),
    }
    if media_type == "movie":
        # Baked date: India theatrical first (fix 2026-10-27) — the
        # TMDB primary date is often a festival premiere in another
        # country, not the India release. NOTE: a title with NO
        # theatrical date anywhere (festival-only, e.g. Hotel Utopia)
        # still bakes its primary date — there is no better date to
        # use, and changing that needs a product decision (it is a
        # world title whose only release IS the festival premiere).
        entry["release_date"] = pick_release_date(details, media_type)
        entry["runtime"] = details.get("runtime") or 0
    else:
        entry["first_air_date"] = details.get("first_air_date") or ""
        networks = [n.get("name") for n in (details.get("networks") or [])
                    if n.get("name")]
        entry["networks"] = networks
        entry["number_of_seasons"] = details.get("number_of_seasons")
        entry["number_of_episodes"] = details.get("number_of_episodes")
        entry["channel"] = networks[0] if networks else ""
        entry["episode_run_time"] = list(
            details.get("episode_run_time") or [])
        entry["seasons"] = [
            {"season_number": s.get("season_number"),
             "episode_count": s.get("episode_count"),
             "air_date": s.get("air_date") or "",
             "name": s.get("name") or ""}
            for s in (details.get("seasons") or [])]
        entry["created_by"] = [c.get("name") for c in
                               (details.get("created_by") or [])
                               if c.get("name")]
    return entry


def main():
    ap = argparse.ArgumentParser(
        description="Publish chosen TMDB titles into js/published-titles.js")
    ap.add_argument("ids", nargs="+", help="TMDB ids to publish")
    ap.add_argument("--key", default=None,
                    help="TMDB API key (or TMDB_API_KEY env var)")
    ap.add_argument("--out", default=DEFAULT_OUT,
                    help="output file (default: js/published-titles.js)")
    ap.add_argument("--categories", default=None,
                    help="comma-separated section keys, e.g. movies,trending")
    ap.add_argument("--published-at", default=None,
                    help="published date YYYY-MM-DD (default: today, UTC)")
    args = ap.parse_args()

    key = args.key or os.environ.get("TMDB_API_KEY")
    if not key:
        print("publish-titles: no TMDB key — set TMDB_API_KEY or --key",
              file=sys.stderr)
        return 2

    today = time.strftime("%Y-%m-%d", time.gmtime())
    published_at = args.published_at or today
    cli_categories = ([c.strip() for c in args.categories.split(",") if c.strip()]
                      if args.categories else None)

    published = read_js_map(args.out, "FA_PUBLISHED")
    added, updated, skipped = 0, 0, 0
    for raw_id in args.ids:
        tid = str(raw_id).strip()
        if not tid.isdigit():
            print(f"  SKIP {raw_id!r}: not a numeric TMDB id")
            skipped += 1
            continue
        try:
            details, media_type = fetch_title(tid, key)
        except Exception as e:
            print(f"  SKIP {tid}: TMDB request failed ({e})")
            skipped += 1
            continue
        if details is None:
            print(f"  SKIP {tid}: no such movie or tv title on TMDB")
            skipped += 1
            continue
        existing = published.get(tid)
        categories = (cli_categories if cli_categories is not None
                      else (existing.get("categories") if existing
                            else (["movies"] if media_type == "movie"
                                  else ["tv"])))
        keep_published_at = (existing.get("published_at")
                             if existing else published_at)
        entry = build_entry(details, media_type, categories,
                            keep_published_at)
        if existing is not None and existing == entry:
            print(f"  unchanged {tid} ({entry['title']}, {media_type})")
            continue
        published[tid] = entry
        trailer = "trailer " + (entry["trailer"]["key"]
                                if entry["trailer"] else "none")
        if existing is not None:
            print(f"  updated {tid} ({entry['title']}, {media_type}, "
                  f"{entry['industry']}, {trailer})")
            updated += 1
        else:
            print(f"  added {tid} ({entry['title']}, {media_type}, "
                  f"{entry['industry']}, {trailer})")
            added += 1

    changed = write_js_map(args.out, "FA_PUBLISHED", published, HEADER)
    print(f"published-titles: +{added} new, {updated} updated, "
          f"{skipped} skipped | file changed: {changed}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

