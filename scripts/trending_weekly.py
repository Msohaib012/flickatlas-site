#!/usr/bin/env python3
"""FlickAtlas — weekly Trending Topics builder (search + AI leg).

Rebuilds js/trending-topics.js (window.FA_TRENDING_TOPICS) once a day.
Strict rule: an entry may appear ONLY if it is trending THIS WEEK
(dated within the last 7 days). Nothing older ever enters the file.

How it works
------------
1. Tavily search (4 focused queries, time_range="week", 5 results
   each — a handful of searches a day, well inside the free quota):
   what is actually trending in entertainment this week.
2. Gemini (same model + key rotation as scripts/gemini_batch.py)
   selects the top 8 topics from the search results + the site's own
   recent articles, and links each topic to a site page (article,
   movie or show page) where one exists, else the site search page.
3. Every entry is validated: its title must share a significant word
   with a search result or a site article headline, and its date must
   be within the last 7 days. Anything ungrounded is dropped, never
   written. If Gemini fails, a deterministic fallback picks the top
   search results instead of writing nothing.

Keys come from the environment (GitHub secrets in Actions):
TAVILY_API_KEY (fallback TAVILY_API_KEY_BACKUP), GEMINI_API_KEY_1..6
(fallback GEMINI_API_KEY). No keys -> print SKIP, exit 0, never break
the pipeline. Keys are never printed or logged.

Deterministic: the output file has no timestamps in its content, so
it is only rewritten when the topics actually change (no spurious
hourly commits). Run daily (nightly trending refresh); do NOT run it
hourly — weekly trending does not change by the hour.
"""
import json
import os
import re
import sys
import urllib.error
import urllib.parse
import urllib.request
from datetime import datetime, timedelta, timezone

try:
    # Per-run record for the stats dashboard (out/step-runs.json).
    # A missing/broken helper must never break this script.
    import step_runs
except Exception:  # noqa: BLE001 - record helper is best-effort
    step_runs = None

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

MODEL = "gemini-3.5-flash-lite"
TAVILY_URL = "https://api.tavily.com/search"
TOP_N = 8
WINDOW_DAYS = 7

QUERIES = [
    "trending Bollywood movies this week box office collection",
    "trending entertainment news India this week",
    "viral movie news this week India",
    "Hollywood trending movies this week box office",
]

HEADER = ("/* FlickAtlas — Trending Topics (this week only). GENERATED by "
          "scripts/trending_weekly.py (Tavily search + Gemini) — do not "
          "edit by hand. Every entry is dated within the last 7 days. */")

STOPWORDS = set("""
a an the and or of to in on for with at by from is are was were be been
this that these those it its as at box office collection day week
movie film news latest today""".split())


def log(msg):
    print(f"trending-weekly: {msg}")


# ---------------------------------------------------------------- keys
def tavily_keys():
    keys = []
    for name in ("TAVILY_API_KEY", "TAVILY_API_KEY_BACKUP"):
        k = os.environ.get(name, "").strip()
        if k:
            keys.append(k)
    return keys


def gemini_keys():
    keys = []
    for i in range(1, 7):
        k = os.environ.get(f"GEMINI_API_KEY_{i}", "").strip()
        if k:
            keys.append(k)
    if not keys:
        k = os.environ.get("GEMINI_API_KEY", "").strip()
        if k:
            keys.append(k)
    return keys


# ------------------------------------------------------------- tavily
def tavily_search(query, keys):
    """One Tavily search, time_range=week. Tries each key in turn."""
    last_err = None
    for key in keys:
        try:
            body = json.dumps({
                "query": query,
                "search_depth": "basic",
                "time_range": "week",
                "max_results": 5,
            }).encode("utf-8")
            req = urllib.request.Request(
                TAVILY_URL, data=body, method="POST",
                headers={"Authorization": "Bearer " + key,
                         "Content-Type": "application/json"})
            with urllib.request.urlopen(req, timeout=30) as r:
                data = json.load(r)
            return data.get("results") or []
        except Exception as e:
            last_err = e
            continue
    log(f"Tavily search failed for {query!r} ({last_err})")
    return []


def search_week(keys):
    """Run the focused queries; return a flat list of results."""
    out = []
    seen = set()
    for q in QUERIES:
        for r in tavily_search(q, keys):
            url = (r.get("url") or "").strip()
            if not url or url in seen:
                continue
            seen.add(url)
            out.append({
                "title": (r.get("title") or "").strip(),
                "url": url,
                "content": (r.get("content") or "").strip(),
            })
    log(f"Tavily: {len(out)} unique week results from {len(QUERIES)} queries")
    return out


# ------------------------------------------------------------- gemini
TOPICS_SCHEMA = {
    "type": "object",
    "properties": {
        "topics": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "title": {"type": "string"},
                    "link_kind": {"type": "string"},
                    "link_ref": {"type": "string"},
                },
                "required": ["title", "link_kind", "link_ref"],
            },
        },
    },
    "required": ["topics"],
}


def call_gemini_json(keys, prompt, schema):
    """Try each key in turn; 429/5xx moves to the next key."""
    last_err = None
    for key in keys:
        try:
            body = json.dumps({
                "contents": [{"parts": [{"text": prompt}]}],
                "generationConfig": {
                    "responseMimeType": "application/json",
                    "responseSchema": schema,
                    "maxOutputTokens": 4096,
                },
            }).encode("utf-8")
            req = urllib.request.Request(
                "https://generativelanguage.googleapis.com/v1beta/models/"
                f"{MODEL}:generateContent",
                data=body,
                headers={"x-goog-api-key": key,
                         "Content-Type": "application/json"})
            with urllib.request.urlopen(req, timeout=90) as r:
                resp = json.load(r)
            text = resp["candidates"][0]["content"]["parts"][0]["text"]
            return json.loads(text)
        except Exception as e:
            last_err = e
            continue
    log(f"Gemini: all keys failed ({last_err})")
    return None


# ------------------------------------------------------------ inputs
def load_js_window(path, varname):
    """Read a js/*.js file that sets window.<varname> = {...}; or [...]."""
    with open(path, encoding="utf-8") as f:
        src = f.read()
    m = re.search(re.escape("window." + varname) + r"\s*=\s*(\{.*\}|\[.*\]);?\s*$",
                  src, re.S)
    if not m:
        return None
    return json.loads(m.group(1))


def parse_date(value):
    """Parse an article `published` string (several spellings) -> date."""
    if not value:
        return None
    try:
        from email.utils import parsedate_to_datetime
        dt = parsedate_to_datetime(str(value))
        if dt is None:
            return None
        return dt.date()
    except Exception:
        return None


def significant_words(text):
    words = re.findall(r"[a-z0-9]+", (text or "").lower())
    return {w for w in words if len(w) > 2 and w not in STOPWORDS}


def recent_articles(root):
    """Site articles from the last 7 days: {id, headline, date}."""
    today = datetime.now(timezone.utc).date()
    cutoff = today - timedelta(days=WINDOW_DAYS)
    try:
        data = load_js_window(os.path.join(root, "js", "articles-data.js"),
                              "FA_ARTICLES")
    except Exception as e:
        log(f"could not read articles-data.js ({e})")
        return []
    if isinstance(data, dict):
        items = list(data.values())
    elif isinstance(data, list):
        items = data
    else:
        return []
    out = []
    for a in items:
        d = parse_date(a.get("published"))
        if d is None or d < cutoff or d > today:
            continue
        h = str(a.get("headline") or a.get("title") or "").strip()
        if not h:
            continue
        out.append({"id": str(a.get("id") or ""), "headline": h,
                    "date": d.isoformat()})
    out.sort(key=lambda x: x["date"], reverse=True)
    log(f"site articles in last 7 days: {len(out)}")
    return out


def published_titles(root):
    """Published titles for linking: {id, type, title}."""
    try:
        data = load_js_window(os.path.join(root, "js", "published-titles.js"),
                              "FA_PUBLISHED")
    except Exception as e:
        log(f"could not read published-titles.js ({e})")
        return []
    if isinstance(data, dict):
        items = list(data.values())
    elif isinstance(data, list):
        items = data
    else:
        return []
    return [{"id": str(t.get("id") or ""), "type": t.get("type") or "movie",
             "title": str(t.get("title") or "").strip()}
            for t in items if t.get("id") and t.get("title")]


# --------------------------------------------------------- selection
def resolve_link(kind, ref, articles, titles):
    """Turn Gemini's link choice into a site URL (or None)."""
    ref = (ref or "").strip()
    if kind == "article":
        for a in articles:
            if a["id"] == ref:
                return "/news-item?id=" + urllib.parse.quote(a["id"])
        return None
    if kind in ("movie", "show"):
        for t in titles:
            if t["id"] == ref and t["type"] == kind:
                return f"/{kind}?id=" + urllib.parse.quote(t["id"])
        return None
    if kind == "search":
        if not ref:
            return None
        return "/search/?q=" + urllib.parse.quote(ref)
    return None


def grounded(title, results, articles):
    """True when the title shares a significant word with a search
    result or a recent site article — i.e. it is traceable, not
    invented."""
    words = significant_words(title)
    if not words:
        return False
    for r in results:
        if words & significant_words(r.get("title", "") + " " +
                                     r.get("content", "")[:400]):
            return True
    for a in articles:
        if words & significant_words(a["headline"]):
            return True
    return False


def _norm(text):
    return re.sub(r"[^a-z0-9]+", " ", (text or "").lower()).strip()


def phrase_grounded(title, texts):
    """Strict grounding: some 2-word phrase of the title must appear
    verbatim in one of the source texts. This catches Gemini garbles
    like 'Surviving Winning Otis Netflix' (no 2-word phrase of it
    exists in any source) while passing honest shortenings of a
    headline ('Jailer 2 Box Office' from 'Jailer 2 Box Office: ...')."""
    words = _norm(title).split()
    if len(words) < 2:
        return bool(words) and any(words[0] in _norm(t) for t in texts)
    bigrams = {" ".join(words[i:i + 2]) for i in range(len(words) - 1)}
    for t in texts:
        hay = _norm(t)
        if any(b in hay for b in bigrams):
            return True
    return False


def gemini_prompt(results, articles, titles):
    lines = ["You select this week's trending entertainment topics for "
             "the FlickAtlas homepage. Use ONLY the items below — never "
             "invent a topic, a title, or a figure.\n",
             "SEARCH RESULTS THIS WEEK (title | url | snippet):"]
    for r in results:
        lines.append(f"- {r['title']} | {r['url']} | "
                     f"{r['content'][:300]}")
    lines.append("\nSITE ARTICLES, LAST 7 DAYS (id | date | headline):")
    for a in articles[:30]:
        lines.append(f"- {a['id']} | {a['date']} | {a['headline']}")
    lines.append("\nPUBLISHED TITLES (id | type | title):")
    for t in titles:
        lines.append(f"- {t['id']} | {t['type']} | {t['title']}")
    lines.append(
        "\nReturn JSON {\"topics\": [{\"title\", \"link_kind\", "
        "\"link_ref\"}]} with at most 8 topics, ranked most-trending "
        "first. Title: copy it closely from the source headline or "
        "search result title — shorten it, do not reword it (e.g. "
        "\"Jailer 2 Box Office Collection Day 12\", \"Ramayana First "
        "Day Advance Booking\"). "
        "link_kind is one of: article (link_ref = site article id), "
        "movie (link_ref = TMDB id), show (link_ref = TMDB id), search "
        "(link_ref = search phrase, only when no site page fits). "
        "Prefer a site article, then a published title, then search. "
        "Skip anything you cannot trace to the inputs above.")
    return "\n".join(lines)


def fallback_topics(results, articles, titles):
    """Deterministic selection when Gemini fails: the site's own
    recent articles (box-office first, then other recent ones),
    newest first. Search results are NOT used here — a generic
    search-result page title (e.g. a section front page) is not a
    trending topic, and linking it to an unrelated site article
    would be misleading. The section stays fresh and truthful from
    site content alone until Gemini is available again."""
    def is_bo(a):
        return "box office" in a["headline"].lower()
    bo = [a for a in articles if is_bo(a)]
    rest = [a for a in articles if not is_bo(a)]
    bo.sort(key=lambda a: a["date"], reverse=True)
    rest.sort(key=lambda a: a["date"], reverse=True)
    topics = []
    for a in (bo + rest)[:TOP_N]:
        topics.append({"title": a["headline"],
                       "url": "/news-item?id=" + urllib.parse.quote(a["id"]),
                       "date": a["date"]})
    return topics


def build_topics(results, articles, titles, gkeys):
    """Gemini selection with validation; deterministic fallback."""
    today = datetime.now(timezone.utc).date()
    topics = []
    if gkeys:
        out = call_gemini_json(gkeys, gemini_prompt(results, articles, titles),
                               TOPICS_SCHEMA)
        if out:
            for item in (out.get("topics") or [])[:TOP_N]:
                title = str(item.get("title") or "").strip()
                if not title:
                    continue
                url = resolve_link(item.get("link_kind"), item.get("link_ref"),
                                   articles, titles)
                if not url:
                    continue
                # Strict phrase grounding: some 2-word phrase of the
                # title must appear verbatim in the linked article
                # headline, a search result, or the linked title name.
                sources = [r.get("title", "") + " " +
                           r.get("content", "")[:400] for r in results]
                for a in articles:
                    if a["id"] and url.endswith(a["id"]):
                        sources.append(a["headline"])
                for t in titles:
                    if t["id"] and url.endswith(t["id"]):
                        sources.append(t["title"])
                if not phrase_grounded(title, sources):
                    log(f"dropping ungrounded topic: {title!r}")
                    continue
                # Date: the linked article's date when available, else today.
                date = today.isoformat()
                for a in articles:
                    if a["id"] and url.endswith(a["id"]):
                        date = a["date"]
                        break
                topics.append({"title": title, "url": url, "date": date})
            log(f"Gemini selected {len(topics)} topics")
    if not topics:
        log("Gemini produced nothing usable — deterministic fallback")
        topics = fallback_topics(results, articles, titles)
    elif len(topics) < 3:
        # Top up from the site's own recent articles (not already used).
        used = {t["url"] for t in topics}
        for extra in fallback_topics(results, articles, titles):
            if extra["url"] not in used:
                topics.append(extra)
                used.add(extra["url"])
            if len(topics) >= 3:
                break
        log(f"topped up to {len(topics)} topics from site articles")
    # Final window guard: drop anything older than 7 days, cap at 8.
    cutoff = today - timedelta(days=WINDOW_DAYS)
    kept = []
    for t in topics:
        d = parse_date(t.get("date"))
        if d is None:
            d = today
        if cutoff <= d <= today:
            kept.append({"title": t["title"], "url": t["url"],
                         "date": d.isoformat()})
        if len(kept) >= TOP_N:
            break
    return kept


# -------------------------------------------------------------- main
def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    root = ROOT
    if "--root" in argv:
        root = argv[argv.index("--root") + 1]
    out_path = os.path.join(root, "js", "trending-topics.js")

    tkeys = tavily_keys()
    if not tkeys:
        log("SKIP: no TAVILY_API_KEY (set TAVILY_API_KEY / "
            "TAVILY_API_KEY_BACKUP) — leaving trending-topics.js alone")
        if step_runs is not None:
            step_runs.record("trending_weekly", status="success",
                             checked={"candidates": 0,
                                      "detail": "Tavily keys missing"},
                             changed={"added": [], "updated": [],
                                      "count": 0},
                             reason="source-fail")
        return 0
    gkeys = gemini_keys()
    if not gkeys:
        log("no Gemini keys — deterministic fallback will be used")

    results = search_week(tkeys)
    if not results:
        log("SKIP: no search results — leaving trending-topics.js alone")
        if step_runs is not None:
            step_runs.record("trending_weekly", status="success",
                             checked={"candidates": 0,
                                      "detail": "Tavily week search "
                                                "returned no results"},
                             changed={"added": [], "updated": [],
                                      "count": 0},
                             reason="source-fail")
        return 0
    articles = recent_articles(root)
    titles = published_titles(root)
    topics = build_topics(results, articles, titles, gkeys)
    if not topics:
        log("SKIP: no grounded topics — leaving trending-topics.js alone")
        if step_runs is not None:
            step_runs.record("trending_weekly", status="success",
                             checked={"candidates": len(results),
                                      "detail": "Tavily week search "
                                                "results, no grounded "
                                                "topics"},
                             changed={"added": [], "updated": [],
                                      "count": 0},
                             reason="no-new-data")
        return 0

    content = (HEADER + "\nwindow.FA_TRENDING_TOPICS = " +
               json.dumps(topics, ensure_ascii=False) + ";\n")
    existing = ""
    if os.path.exists(out_path):
        with open(out_path, encoding="utf-8") as f:
            existing = f.read()
    if existing == content:
        log(f"trending-topics.js unchanged ({len(topics)} topics)")
        if step_runs is not None:
            step_runs.record("trending_weekly", status="success",
                             checked={"candidates": len(results),
                                      "detail": "Tavily week search results"},
                             changed={"added": [], "updated": [],
                                      "count": 0},
                             reason="no-new-data")
        return 0
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(content)
    log(f"trending-topics.js written ({len(topics)} topics)")
    for t in topics:
        log(f"  - {t['date']} {t['title']} -> {t['url']}")
    if step_runs is not None:
        step_runs.record("trending_weekly", status="success",
                         checked={"candidates": len(results),
                                  "detail": "Tavily week search results"},
                         changed={"added": [t.get("title") for t in topics],
                                  "updated": [], "count": len(topics)})
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

