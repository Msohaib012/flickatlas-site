#!/usr/bin/env python3
"""Build js/ott-data.js — the OTT section's data file (owner order 2026-10-27).

Reads the published catalogue (js/published-titles.js) and classifies
every title that has TMDB flatrate (streaming) providers into two groups:

  now    — providers present AND release/air date is today or earlier
           (the film/series has arrived on streaming).
  coming — providers present AND release/air date is in the future
           (the platform is announced; the title has not arrived yet).

Each entry is {id, type, providers: [{name, logo_path}], date,
date_kind}. `date` is ALWAYS the title's theatrical/first release
date and `date_kind` is ALWAYS "release" — the site never invents an
OTT premiere date. Pages must label it as the release date ("Released
23 October 2026" / "Releasing 29 October 2026"), never as a streaming
start date.

Deterministic output (sorted keys, fixed entry order, no timestamps):
the file is written only when its bytes actually change, so the hourly
pipeline never makes a spurious commit. No TMDB calls — providers are
baked into FA_PUBLISHED by the seeder (scripts/title-seed.py) and the
backfill (scripts/backfill_providers.py); this script only classifies.

Usage:
  python3 scripts/build_ott.py [--published js/published-titles.js]
                               [--out js/ott-data.js] [--dry-run]
  --dry-run prints what it would write, writes nothing.
Imported by scripts/title-seed.py (end of main): the seeder rebuilds
ott-data.js on every run so new titles with providers join the OTT
section automatically.
"""
import argparse
import importlib.util
import os
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_PUBLISHED = os.path.join(ROOT, "js", "published-titles.js")
DEFAULT_OUT = os.path.join(ROOT, "js", "ott-data.js")
PUBLISH_TITLES = os.path.join(ROOT, "scripts", "publish-titles.py")

HEADER = (
    "/* FlickAtlas — OTT section data. GENERATED by scripts/build_ott.py "
    "(run by scripts/title-seed.py on every seeder run) — do not edit by "
    "hand. Two groups from the published catalogue: now = streaming "
    "providers present and released; coming = providers present and "
    "release date in the future. `date` is the title's release date "
    "(date_kind \"release\") — never an invented OTT premiere date. */\n"
)


def load_publish_titles():
    """Import scripts/publish-titles.py by path (hyphenated filename)."""
    spec = importlib.util.spec_from_file_location("publish_titles",
                                                  PUBLISH_TITLES)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def classify(published, today):
    """Split provider-carrying titles into now / coming groups."""
    now, coming, dateless = [], [], []
    for tid, entry in published.items():
        if not isinstance(entry, dict):
            continue
        providers = entry.get("providers") or []
        if not providers:
            continue
        date = (entry.get("release_date") or entry.get("first_air_date")
                or "")
        if not date:
            dateless.append(entry.get("title") or str(tid))
            continue
        clean_providers = []
        for p in providers:
            name = (p.get("name") or "").strip()
            if not name:
                continue
            clean_providers.append({
                "name": name,
                "logo_path": p.get("logo_path") or "",
            })
        if not clean_providers:
            continue
        item = {
            "id": entry.get("id"),
            "type": "tv" if entry.get("type") == "tv" else "movie",
            "providers": clean_providers,
            "date": date,
            "date_kind": "release",
        }
        if date <= today:
            now.append(item)
        else:
            coming.append(item)
    # now: newest release first; coming: nearest release first.
    now.sort(key=lambda x: (x["date"], str(x["id"])), reverse=True)
    coming.sort(key=lambda x: (x["date"], str(x["id"])))
    return now, coming, dateless


def render(now, coming):
    import json
    payload = {"now": now, "coming": coming}
    return (HEADER + "window.FA_OTT = "
            + json.dumps(payload, indent=2, sort_keys=True) + ";\n")


def build(out_path, published_path, dry_run=False):
    """Rebuild ott-data.js from the published catalogue.

    Returns (now_count, coming_count, changed_bool). Never raises for
    missing data — an empty catalogue yields empty groups.
    """
    pt = load_publish_titles()
    try:
        published = pt.read_js_map(published_path, "FA_PUBLISHED")
    except Exception as e:
        print(f"build-ott: cannot read {published_path} ({e})",
              file=sys.stderr)
        return 0, 0, False
    today = time.strftime("%Y-%m-%d", time.gmtime())
    now, coming, dateless = classify(published, today)
    for title in dateless:
        print(f"build-ott: skipped {title} (providers but no date)",
              file=sys.stderr)
    text = render(now, coming)
    if dry_run:
        print(f"build-ott (dry run): now {len(now)}, coming "
              f"{len(coming)} | file NOT written")
        return len(now), len(coming), False
    old = ""
    if os.path.exists(out_path):
        with open(out_path, encoding="utf-8") as f:
            old = f.read()
    if old == text:
        print(f"build-ott: now {len(now)}, coming {len(coming)} | "
              f"unchanged")
        return len(now), len(coming), False
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"build-ott: now {len(now)}, coming {len(coming)} | "
          f"wrote {out_path}")
    return len(now), len(coming), True


def main():
    ap = argparse.ArgumentParser(
        description="Build js/ott-data.js from js/published-titles.js")
    ap.add_argument("--published", default=DEFAULT_PUBLISHED,
                    help="published catalogue (default: "
                         "js/published-titles.js)")
    ap.add_argument("--out", default=DEFAULT_OUT,
                    help="output file (default: js/ott-data.js)")
    ap.add_argument("--dry-run", action="store_true",
                    help="print what it would do, do NOT write the file")
    args = ap.parse_args()
    build(args.out, args.published, args.dry_run)
    return 0


if __name__ == "__main__":
    sys.exit(main())
