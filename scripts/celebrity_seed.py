#!/usr/bin/env python3
"""Seed Celebrity Today (js/celebrity-data.js) from TMDB trending people.

Why this exists (verified 2026-10-26): js/celebrity-data.js was generated
once (2026-10-22T23:07:50Z) by an external "live data engine"
(pipeline/export_celebrity.py) that was NEVER committed to any repo
(no pipeline/ dir, no export_celebrity.py, and no workflow or script in
the site repo or the Flickposts panel repo references "celebrity" at all).
The file was mirrored into the repo once (commit 040816a7, 2026-10-24)
and nothing regenerates it. The site only shows feed items <24h fresh,
so Celebrity Today has rendered NOTHING since 2026-10-23.

This script replaces that dead pipeline with a TMDB data reader:
  - GET /trending/person/day (who is trending TODAY — the right signal
    for "Celebrity Today"), page 1.
  - Keep people with a profile image, top COUNT (default 8 — the
    homepage shows at most 8).
  - For each person, GET /person/{id}/combined_credits and take the
    most popular MOVIE credit as the "known for" title (movie-first:
    sorting all credits by popularity picks talk-show / variety guest
    spots, e.g. Tom Cruise -> "Running Man", Jim Carrey -> "The Tonight
    Show"; the movie filter avoids that). Falls back to any credit, then
    to the person's known_for_department.
  - Writes js/celebrity-data.js in the EXACT existing format
    (window.FA_CELEBRITY_TODAY = {generated_at, items: [{celebrity,
    tmdb_person_id, what, where, category, when, source, source_url}]})
    so js/page-celebrity-today.js, js/page-celebrities.js and
    UI.celebTodaySection need no change.

Field values (honest, all from TMDB):
  - what: "trending — known for <title>" (renders as "Name trending
    known for <title>"); fallback "trending — <department>".
  - where: "Trending today" (no place applies to a trending signal).
  - category: "trending" (no consumer filters on it).
  - when: run time, staggered 1 min per rank so the newest-first sort
    reflects the trending rank.
  - source: "TMDB"; source_url: the TMDB person page (unique per
    person, feeds UI.celebItemId).

Fallback: if /trending/person/day yields <3 usable people (or fails),
fill from /person/popular page 1 (which carries known_for inline, so no
extra credits call is needed for those).

Safety:
  - Never writes an empty items list (a failed run leaves the old file
    untouched rather than blanking the section).
  - Any single person's credits call failing falls back to the
    department label; it never aborts the run.
  - Default is --dry-run (print what would be written, write nothing).
    Use --apply to write.

Usage:
  python3 scripts/celebrity_seed.py [--apply] [--count N]
      [--key KEY] [--root REPO_ROOT]
  The key comes from --key, TMDB_API_KEY, or js/config.js (TMDB_KEY) —
  same order as scripts/title-seed.py. Run daily (celebrities change
  slowly; the <24h freshness rule means the file must be rewritten at
  least once a day).
"""

import json
import os
import re
import sys
import time
import urllib.error
import urllib.request
from datetime import datetime, timedelta, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONFIG_JS = os.path.join(ROOT, "js", "config.js")
OUT_JS = os.path.join(ROOT, "js", "celebrity-data.js")

TMDB_BASE = "https://api.themoviedb.org/3"
DEFAULT_COUNT = 8
MIN_ITEMS = 3  # below this, fall back to /person/popular

HEADER = """/* FlickAtlas — Celebrity Today items. GENERATED by
   scripts/celebrity_seed.py from TMDB trending people — do not edit by
   hand. The site shows these only while fresh (< 24h). */
"""


def get_key(args_key=None):
    """TMDB key: --key, then TMDB_API_KEY, then js/config.js TMDB_KEY."""
    if args_key:
        return args_key.strip()
    env = os.environ.get("TMDB_API_KEY", "").strip()
    if env:
        return env
    try:
        with open(CONFIG_JS, encoding="utf-8") as f:
            raw = f.read()
        m = re.search(r'TMDB_KEY:\s*"([^"]+)"', raw)
        if m:
            return m.group(1)
    except OSError:
        pass
    return ""


def tmdb_get(key, path):
    """GET one TMDB endpoint. Returns parsed JSON, or None on failure."""
    url = TMDB_BASE + path + ("&" if "?" in path else "?") + "api_key=" + key + "&language=en-US"
    req = urllib.request.Request(url, headers={"Accept": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=20) as r:
            return json.loads(r.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        print(f"  TMDB {e.code} on {path}", file=sys.stderr)
    except Exception as e:  # noqa: BLE001 - network errors must not crash
        print(f"  TMDB error on {path}: {e}", file=sys.stderr)
    return None


def known_for_title(key, person_id, department):
    """Most popular MOVIE credit for a person -> title, or None.

    Movie-first: sorting ALL credits by popularity picks talk-show /
    variety guest spots (Tom Cruise -> "Running Man", Jim Carrey ->
    "The Tonight Show"). The movie filter avoids that.
    """
    data = tmdb_get(key, f"/person/{person_id}/combined_credits")
    if not data:
        return None
    for pool in (data.get("cast") or [], data.get("crew") or []):
        movies = [c for c in pool
                  if c.get("media_type") == "movie"
                  and (c.get("title") or "").strip()]
        movies.sort(key=lambda c: c.get("popularity", 0), reverse=True)
        if movies:
            return movies[0]["title"].strip()
    for pool in (data.get("cast") or [], data.get("crew") or []):
        any_ = [c for c in pool
                if (c.get("title") or c.get("name") or "").strip()]
        any_.sort(key=lambda c: c.get("popularity", 0), reverse=True)
        if any_:
            return (any_[0].get("title") or any_[0].get("name")).strip()
    return None


def build_item(key, person, rank, run_time):
    """One trending person -> a feed item in the existing format."""
    pid = person["id"]
    name = (person.get("name") or "").strip()
    dept = (person.get("known_for_department") or "").strip()
    title = known_for_title(key, pid, dept)
    if title:
        what = f"trending — known for {title}"
    elif dept:
        what = f"trending — {dept}"
    else:
        what = "trending today"
    # Stagger `when` 1 min per rank so the newest-first sort reflects
    # the trending rank (all items are from the same run).
    when = run_time - timedelta(minutes=rank)
    return {
        "celebrity": name,
        "tmdb_person_id": int(pid),
        "what": what,
        "where": "Trending today",
        "category": "trending",
        "when": when.astimezone(timezone.utc).isoformat(),
        "source": "TMDB",
        "source_url": f"https://www.themoviedb.org/person/{pid}",
    }


def fetch_trending(key, count):
    """Top `count` trending people with a profile image."""
    data = tmdb_get(key, "/trending/person/day")
    if not data:
        return []
    out = []
    for p in data.get("results") or []:
        if not p.get("id") or not (p.get("name") or "").strip():
            continue
        if not p.get("profile_path"):
            continue  # the person page needs a photo
        out.append(p)
        if len(out) >= count:
            break
    return out


def fetch_popular(key, count, exclude_ids):
    """Fill-up from /person/popular (carries known_for inline)."""
    data = tmdb_get(key, "/person/popular")
    if not data:
        return []
    out = []
    for p in data.get("results") or []:
        if not p.get("id") or p["id"] in exclude_ids:
            continue
        if not (p.get("name") or "").strip() or not p.get("profile_path"):
            continue
        out.append(p)
        if len(out) >= count:
            break
    return out


def build_items(key, count, run_time):
    """Trending people -> feed items (with popular fallback)."""
    people = fetch_trending(key, count)
    if len(people) < MIN_ITEMS:
        print(f"  trending gave {len(people)} usable people (< {MIN_ITEMS}); "
              "filling from /person/popular")
        have = {p["id"] for p in people}
        people += fetch_popular(key, count - len(people), have)
        people = people[:count]
    items = []
    for rank, p in enumerate(people):
        # Popular-fallback people carry known_for inline — use it
        # directly instead of an extra credits call.
        kf = p.get("known_for") or []
        title = None
        if kf:
            first = kf[0] or {}
            title = (first.get("title") or first.get("name") or "").strip() or None
        if title:
            when = run_time - timedelta(minutes=rank)
            items.append({
                "celebrity": (p.get("name") or "").strip(),
                "tmdb_person_id": int(p["id"]),
                "what": f"trending — known for {title}",
                "where": "Trending today",
                "category": "trending",
                "when": when.astimezone(timezone.utc).isoformat(),
                "source": "TMDB",
                "source_url": f"https://www.themoviedb.org/person/{p['id']}",
            })
        else:
            items.append(build_item(key, p, rank, run_time))
        time.sleep(0.3)  # TMDB rate limit is 40 req / 10 s
    return items


def render_js(generated_at, items):
    """The file content in the exact existing format."""
    payload = {"generated_at": generated_at, "items": items}
    return HEADER + "window.FA_CELEBRITY_TODAY = " + \
        json.dumps(payload, indent=2, ensure_ascii=False) + ";\n"


def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(description="Seed Celebrity Today from TMDB trending people.")
    ap.add_argument("--apply", action="store_true",
                    help="write js/celebrity-data.js (default: dry-run)")
    ap.add_argument("--count", type=int, default=DEFAULT_COUNT,
                    help="how many people to include (default 8)")
    ap.add_argument("--key", default=None, help="TMDB API key")
    ap.add_argument("--root", default=ROOT, help="repo root (default: parent of scripts/)")
    args = ap.parse_args(argv)

    global CONFIG_JS, OUT_JS  # noqa: PLW0603 - root override for testing
    CONFIG_JS = os.path.join(args.root, "js", "config.js")
    OUT_JS = os.path.join(args.root, "js", "celebrity-data.js")

    key = get_key(args.key)
    if not key:
        print("ERROR: no TMDB key (use --key, TMDB_API_KEY, or js/config.js)",
              file=sys.stderr)
        return 2

    run_time = datetime.now(timezone.utc)
    print(f"celebrity seed: run {run_time.isoformat()}, count={args.count}")
    items = build_items(key, args.count, run_time)
    if not items:
        print("ERROR: no usable trending people — writing nothing "
              "(old file left untouched)", file=sys.stderr)
        return 1
    print(f"  {len(items)} items:")
    for it in items:
        print(f"    {it['celebrity']} (id {it['tmdb_person_id']}): "
              f"{it['what']} @ {it['when']}")

    content = render_js(run_time.isoformat(), items)
    if not args.apply:
        print("  dry-run: not writing (use --apply to write "
              f"{OUT_JS})")
        return 0
    with open(OUT_JS, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"  wrote {OUT_JS} ({len(items)} items)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
