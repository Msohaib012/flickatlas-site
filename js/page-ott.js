/* FlickAtlas — OTT hub (/ott): the SEPARATE OTT section (owner order
   2026-10-27). OTT lives ONLY here — never mixed into Movies or Box
   Office. Two groups from window.FA_OTT (generated by
   scripts/build_ott.py from the published catalogue):
   Now on OTT (streaming providers present, released) and Coming to OTT
   (confirmed digital streaming dates; movie release dates may also be
   shown when a platform is announced). TV series need a confirmed future
   OTT date and are never inferred from a future premiere alone. Industry
   filter (?f=): All / Bollywood / World Cinema — the same definitions
   as /box-office (Bollywood = industry "bollywood" OR origin_country
   includes "IN"; World Cinema = industry "world" AND NOT Indian).
   Type filter (?t=, TV order 2026-10-27): Movies / TV Series / All —
   default Movies. Industry rule 2026-10-28: TV follows the SAME
   industry gate as movies (Bollywood = all India-related, World
   Cinema = only international. Pakistani dramas NEVER appear on
   OTT (owner correction 2026-10-28 21:10: dramas are a separate
   category, YouTube-sourced — OTT carries only movies + TV series). Both filters
   are .fa-select in-page dropdowns (See All filters are dropdowns,
   never a native <select> popup). Each card shows the OTT platform
   logo + names and the date — the confirmed streaming date where TMDB
   reports one, otherwise the title's release date; the site never
   invents an OTT premiere date. Coming cards take the Coming Soon
   look (bare date + Movie/TV + rating badge) with the OTT logo
   alongside. Published-only; falls back to deriving the groups from
   FA_PUBLISHED when ott-data.js has not loaded. No watch or
   download buttons; availability is text and logos only, never links. */
(async function () {
  UI.mountChrome("/ott");
  const main = document.getElementById("app");
  UI.setSEO({
    title: "OTT — Now Streaming & Coming Soon | FlickAtlas",
    desc: "Which movies have arrived on streaming and which are coming — platform logos and release dates for Bollywood and World Cinema, as information only.",
    path: "/ott"
  });

  let f = UI.getParam("f", "all");
  if (!["bollywood", "international"].includes(f)) f = "all";
  /* TV order 2026-10-27: Type filter (?t=), default Movies — the
     homepage OTT See All link carries ?t=. Industry rule 2026-10-28:
     TV follows the SAME industry gate as movies (see inFilter);
     the 2026-10-27 "TV ignores industry" rule is superseded. */
  let t = UI.getParam("t", "movie");
  if (!["movie", "tv", "all"].includes(t)) t = "movie";
  /* Industry rule (owner order 2026-10-28): Bollywood = ALL Indian
     titles, World Cinema = only international — canonical
     UI.industryOf(). TV follows the SAME gate as movies.
     Owner correction 2026-10-28 21:10: Pakistani dramas are a SEPARATE
     category (YouTube-sourced), NOT TV series — they NEVER appear on
     OTT, not even under f=all. Excluded CATEGORICALLY here, not via
     providers or the industry gate: all 15 catalogue "TV" entries
     today are Pakistani dramas. */
  const inFilter = (x) => {
    if (UI.industryOf(x) === "pakistani") return false;
    if (t === "movie" && (x.type || "movie") !== "movie") return false;
    if (t === "tv" && (x.type || "movie") !== "tv") return false;
    return f === "all" ? true
      : f === "bollywood" ? UI.industryOf(x) === "bollywood"
      : UI.industryOf(x) === "world";
  };
  /* Local tag dropped 2026-10-28 (merge): the fixed UI.industryTag()
     now labels Indian titles correctly, so the canonical tag is used. */
  const tagFor = (x) => UI.industryTag(x);
  const today = UI.todayPKT();
  /* Groups: FA_OTT first; derive the same groups from FA_PUBLISHED
     when ott-data.js has not loaded, so the page never goes blank. */
  function deriveFromPublished() {
    const now = [], coming = [];
    for (const x of Object.values(window.FA_PUBLISHED || {})) {
      if (!x || !x.id || !x.poster_path || !(x.providers || []).length) continue;
      const isTv = (x.type || "movie") === "tv";
      if (isTv) {
        const air = x.first_air_date || "";
        if (air && air <= today) now.push({ id: x.id, type: "tv", providers: x.providers, date: air, date_kind: "release" });
        const d = String(x.ott_release_date || "");
        const planned = String(x.ott_release_provider || "").trim().toLowerCase();
        const sources = Array.isArray(x.ott_release_source) ? x.ott_release_source : [x.ott_release_source];
        const hasSource = sources.some(u => typeof u === "string" && u.trim().startsWith("https://"));
        const matching = x.providers.filter(pr => pr && planned && String(pr.name || "").trim().toLowerCase() === planned);
        if (/^\d{4}-\d{2}-\d{2}$/.test(d) && d > today && hasSource && matching.length) {
          coming.push({ id: x.id, type: "tv", providers: matching.slice(0, 1), date: d, date_kind: "digital" });
        }
        continue;
      }
      const d = x.release_date || "";
      if (d && d <= today) now.push({ id: x.id, type: "movie", providers: x.providers, date: d, date_kind: "release" });
      // A future theatrical release date is not an OTT release date.
    }
    now.sort((a, b) => b.date.localeCompare(a.date));
    coming.sort((a, b) => a.date.localeCompare(b.date));
    return { now, coming };
  }
  const ott = window.FA_OTT;
  const groups = (ott && Array.isArray(ott.now) && Array.isArray(ott.coming))
    ? ott : deriveFromPublished();
  const pub = window.FA_PUBLISHED || {};
  const entriesFor = (group, groupName) => (group || [])
    .map(g => ({ g, x: pub[String(g.id)] }))
    .filter(({ g, x }) => {
      if (!x || !x.poster_path || !Array.isArray(g.providers) || !g.providers.length) return false;
      if (!/^\d{4}-\d{2}-\d{2}$/.test(String(g.date || ""))) return false;
      const isTv = (x.type || "movie") === "tv";
      if (isTv) {
        if (UI.industryOf(x) === "pakistani") return false;
        const air = String(x.first_air_date || "");
        if (!/^\d{4}-\d{2}-\d{2}$/.test(air)) return false;
        if (groupName === "now" && (air > today || g.date !== air)) return false;
        if (groupName === "coming") {
          const planned = String(x.ott_release_provider || "").trim().toLowerCase();
          const sources = Array.isArray(x.ott_release_source) ? x.ott_release_source : [x.ott_release_source];
          const hasSource = sources.some(u => typeof u === "string" && u.trim().startsWith("https://"));
          const providerMatches = g.providers.some(pr => pr && planned && String(pr.name || "").trim().toLowerCase() === planned);
          if (g.date <= today || g.date !== x.ott_release_date || !hasSource || !providerMatches || !["digital", "streaming", "ott"].includes(String(g.date_kind || "").toLowerCase())) return false;
        }
      } else if (groupName === "coming" && String(g.date_kind || "").toLowerCase() !== "digital") {
        return false;
      }
      if (groupName === "now" && g.date > today) return false;
      if (groupName === "coming" && g.date <= today) return false;
      return true;
    })
    .filter(({ x }) => inFilter(x))
    .sort((a, b) => groupName === "now" ? String(b.g.date).localeCompare(String(a.g.date)) : String(a.g.date).localeCompare(String(b.g.date)));
  const cardHtml = ({ g, x }) => UI.ottCard(x, {
    coming: (g.date || "") > today,
    providers: g.providers,
    tag: tagFor(x),
    date: g.date,
    dateKind: g.date_kind,
  });
  /* Empty states name the active filters (2026-10-28: a bare
     "Nothing reported here yet" never said which Industry/Type was
     empty). */
  const emptyNote = (coming) => {
    const typeNoun = t === "tv" ? "TV series" : t === "all" ? "titles" : "movies";
    const indNoun = f === "all" ? "any industry" : f === "bollywood" ? "Bollywood" : "World Cinema";
    return coming
      ? `No upcoming OTT releases reported for ${indNoun} ${typeNoun} yet — new titles join automatically when streaming availability is confirmed.`
      : `${t === "tv" ? "No TV series currently streaming on OTT" : `No ${typeNoun} streaming on OTT`} for ${indNoun} yet — new titles join automatically when streaming availability is confirmed.`;
  };
  const groupHtml = (title, note, list, coming) => `<div class="ott-group"><h3>${title} (${list.length})</h3>
    <p class="ott-group-note">${note}</p>
    ${list.length
      ? `<div class="grid">${list.map(cardHtml).join("")}</div>`
      : `<p class="prov-note">${emptyNote(coming)}</p>`}
  </div>`;

  const nowList = entriesFor(groups.now, "now");
  const comingList = entriesFor(groups.coming, "coming");

  function renderGroups() {
    const now = entriesFor(groups.now, "now");
    const coming = entriesFor(groups.coming, "coming");
    main.querySelector("#ottGroups").innerHTML =
      groupHtml("Now on OTT", "Streaming now — platform logos shown per title.", now, false)
      + groupHtml("Coming to OTT", "Movies appear only with a confirmed digital date; TV series need a source-backed OTT date and matching platform.", coming, true);
  }

  main.innerHTML = `<div class="wrap">
    <div class="page-hero"><h1>OTT</h1>
      <p>Which movies and TV series have arrived on streaming, and which are coming — platform logos and release dates, as information only.</p></div>
    <div id="chipHost"><div class="listing-select-row">
      <div class="filter-select" role="group" aria-labelledby="indSelectLabel"><span class="filter-select-label" id="indSelectLabel">Industry</span><div class="fa-select"><button type="button" class="fa-select-trigger" id="indTrigger" role="combobox" aria-haspopup="listbox" aria-expanded="false" aria-controls="indOptions" aria-labelledby="indSelectLabel indValue"><span class="fa-select-value" id="indValue"></span><span class="fa-select-chevron" aria-hidden="true"></span></button><div class="fa-select-menu" id="indOptions" role="listbox" aria-labelledby="indSelectLabel" hidden></div></div></div>
      <div class="filter-select" role="group" aria-labelledby="typeSelectLabel"><span class="filter-select-label" id="typeSelectLabel">Type</span><div class="fa-select"><button type="button" class="fa-select-trigger" id="typeTrigger" role="combobox" aria-haspopup="listbox" aria-expanded="false" aria-controls="typeOptions" aria-labelledby="typeSelectLabel typeValue"><span class="fa-select-value" id="typeValue"></span><span class="fa-select-chevron" aria-hidden="true"></span></button><div class="fa-select-menu" id="typeOptions" role="listbox" aria-labelledby="typeSelectLabel" hidden></div></div></div>
    </div></div>
    <div id="ottGroups">
    ${groupHtml("Now on OTT", "Streaming now — platform logos shown per title.", nowList, false)}
    ${groupHtml("Coming to OTT", "Movies appear only with a confirmed digital date; TV series need a source-backed OTT date and matching platform.", comingList, true)}
    </div>
    <p class="prov-note">FlickAtlas does not stream video and does not link to any platform. Provider names and logos come from TMDB watch/providers data for published titles only; availability is per-title and changes over time.</p>
  </div>`;
  const chipHost = main.querySelector("#chipHost");
  UI.mountFaSelect(chipHost.querySelectorAll(".filter-select")[0],
    [{ value: "all", label: "All industries" }, { value: "bollywood", label: "Bollywood" }, { value: "international", label: "World Cinema" }],
    f, (v) => { f = v; UI.setParam("f", f === "all" ? "" : f); renderGroups(); });
  UI.mountFaSelect(chipHost.querySelectorAll(".filter-select")[1],
    [{ value: "movie", label: "Movies" }, { value: "tv", label: "TV Series" }, { value: "all", label: "All" }],
    t, (v) => { t = v; UI.setParam("t", t === "movie" ? "" : t); renderGroups(); });
})();

