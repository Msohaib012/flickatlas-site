/* FlickAtlas — OTT hub (/ott): the SEPARATE OTT section (owner order
   2026-10-27). OTT lives ONLY here — never mixed into Movies or Box
   Office. Two groups from window.FA_OTT (generated by
   scripts/build_ott.py from the published catalogue):
   Now on OTT (streaming providers present, released) and Coming to OTT
   (providers present, release date in the future). Industry filter
   (?f=): All / Bollywood / World Cinema — the same definitions as
   /box-office (Bollywood = industry "bollywood" OR origin_country
   includes "IN"; World Cinema = industry "world" AND NOT Indian).
   Each card shows the OTT platform logo + names and the release date,
   labelled as the release date — the site never invents an OTT
   premiere date. Published-only; falls back to deriving the groups
   from FA_PUBLISHED when ott-data.js has not loaded. No watch or
   download buttons; availability is text and logos only, never links. */
(async function () {
  UI.mountChrome("/ott");
  const main = document.getElementById("app");
  UI.setSEO({
    title: "OTT — Now Streaming & Coming Soon | FlickAtlas",
    desc: "Which movies have arrived on streaming and which are coming — platform logos and release dates for Bollywood and World Cinema, as information only.",
    path: "/ott"
  });

  let f = UI.getParam("f", "all");
  if (!["bollywood", "international"].includes(f)) f = "all";
  const isIndian = (x) => (x.origin_country || []).includes("IN");
  /* Bollywood and World Cinema are mutually exclusive: an Indian film
     belongs in Bollywood even when the seeder filed it under industry
     "world", so World Cinema excludes Indian titles too (same rule as
     /box-office). */
  const inFilter = (x) => f === "all" ? true
    : f === "bollywood" ? (x.industry === "bollywood" || isIndian(x))
    : (x.industry === "world" && !isIndian(x));
  const tagFor = (x) => (x && x.industry === "world") ? "World Cinema" : UI.industryTag(x);
  const today = new Date().toISOString().slice(0, 10);

  /* Groups: FA_OTT first; derive the same groups from FA_PUBLISHED
     when ott-data.js has not loaded, so the page never goes blank. */
  function deriveFromPublished() {
    const now = [], coming = [];
    for (const x of Object.values(window.FA_PUBLISHED || {})) {
      if (!x || !x.id || !x.poster_path || !(x.providers || []).length) continue;
      const d = x.release_date || x.first_air_date || "";
      if (!d) continue;
      (d <= today ? now : coming).push({
        id: x.id, type: x.type || "movie", providers: x.providers,
        date: d, date_kind: "release",
      });
    }
    now.sort((a, b) => b.date.localeCompare(a.date));
    coming.sort((a, b) => a.date.localeCompare(b.date));
    return { now, coming };
  }
  const ott = window.FA_OTT;
  const groups = (ott && Array.isArray(ott.now) && Array.isArray(ott.coming))
    ? ott : deriveFromPublished();
  const pub = window.FA_PUBLISHED || {};
  const entriesFor = (group) => (group || [])
    .map(g => ({ g, x: pub[String(g.id)] }))
    .filter(({ x }) => x && x.poster_path)
    .filter(({ x }) => inFilter(x));
  const cardHtml = ({ g, x }) => UI.ottCard(x, {
    coming: (g.date || "") > today,
    providers: g.providers,
    tag: tagFor(x),
  });
  const groupHtml = (title, note, list) => `<div class="ott-group"><h3>${title} (${list.length})</h3>
    <p class="ott-group-note">${note}</p>
    ${list.length
      ? `<div class="grid">${list.map(cardHtml).join("")}</div>`
      : `<p class="prov-note">Nothing reported here yet — new titles join automatically when streaming availability is confirmed.</p>`}
  </div>`;

  const nowList = entriesFor(groups.now);
  const comingList = entriesFor(groups.coming);

  main.innerHTML = `<div class="wrap">
    <div class="page-hero"><h1>OTT</h1>
      <p>Which movies have arrived on streaming, and which are coming — platform logos and release dates, as information only.</p></div>
    <nav class="bo-scope" aria-label="OTT industry"><a class="chip${f === "all" ? " on" : ""}" href="/ott"${f === "all" ? ' aria-current="page"' : ""}>All industries</a><a class="chip${f === "bollywood" ? " on" : ""}" href="/ott?f=bollywood"${f === "bollywood" ? ' aria-current="page"' : ""}>Bollywood</a><a class="chip${f === "international" ? " on" : ""}" href="/ott?f=international"${f === "international" ? ' aria-current="page"' : ""}>World Cinema</a></nav>
    ${groupHtml("Now on OTT", "Streaming now — platform logos shown per title.", nowList)}
    ${groupHtml("Coming to OTT", "Platform announced — the date shown is the title's release date, not a streaming start date.", comingList)}
    <p class="prov-note">FlickAtlas does not stream video and does not link to any platform. Provider names and logos come from TMDB watch/providers data for published titles only; availability is per-title and changes over time.</p>
  </div>`;
})();
